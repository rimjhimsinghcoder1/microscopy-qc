"""Write reports/results.md from a run's saved outputs.

Numbers in documentation are generated, never typed by hand, so they cannot
drift away from the run they describe.
"""

import json
from pathlib import Path

from mqc.report import LABELS


def _label(name: str) -> str:
    return LABELS.get(name, name)


def render(run_dir: str | Path) -> str:
    run_dir = Path(run_dir)
    summary = json.loads((run_dir / "summary.json").read_text())
    report = json.loads((run_dir / "report" / "report.json").read_text())
    prov = json.loads((run_dir / "provenance.json").read_text())
    git = prov["git"]
    commit = (git["commit"] or "unknown")[:7]
    dirty = " (uncommitted changes)" if git["dirty"] else ""

    lines = [
        "# Results",
        "",
        "_Generated by `make report`. Do not edit by hand._",
        "",
        f"- Run: `{run_dir.name}`",
        f"- Code: commit `{commit}`{dirty}",
        f"- Dataset MD5: `{prov['dataset_md5']}`",
        f"- Environment: Python {prov['python']}, {prov['platform']}",
        "",
        "## Accuracy",
        "",
        "Test set: 300 images (75 per class). 95% CI from 2,000 bootstrap resamples.",
        "",
        "| Model | Val acc | Test acc | Test 95% CI | Test macro-F1 |",
        "|---|---|---|---|---|",
    ]
    for name, s in summary.items():
        t, v = s["test"], s["val"]
        lo, hi = t["accuracy_95ci"]
        lines.append(
            f"| {_label(name)} | {v['accuracy']:.3f} | {t['accuracy']:.3f} "
            f"| {lo:.3f}-{hi:.3f} | {t['macro_f1']:.3f} |"
        )

    target = report["target_auto_accuracy"]
    lines += [
        "",
        f"## Human-review policy (target {target:.0%} on auto-decided images)",
        "",
        "Threshold and temperature chosen on validation; numbers below are test.",
        "",
        "| Model | Temperature | ECE before | ECE after | Auto-decided "
        "| Accuracy when auto | Errors sent to review |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, r in report["models"].items():
        rp = r["review_policy_test"]
        auto = "-" if rp["auto_accuracy"] is None else f"{rp['auto_accuracy']:.1%}"
        mark = " **(recommended)**" if name == report["recommended_model"] else ""
        lines.append(
            f"| {_label(name)}{mark} | {r['temperature']:.2f} "
            f"| {r['test_ece_before']:.3f} | {r['test_ece_after']:.3f} "
            f"| {rp['auto_decided_frac']:.1%} | {auto} "
            f"| {rp['errors_caught_by_review']} of {rp['total_errors']} |"
        )

    degraded = _degraded_classes(run_dir, next(iter(summary)))
    lines += [
        "",
        "## Recall on the mildest third of each degradation (test)",
        "",
        "| Model | " + " | ".join(c.capitalize() for c in degraded) + " |",
        "|---|" + "---|" * len(degraded),
    ]
    for name in summary:
        sev = json.loads((run_dir / name / "metrics.json").read_text())["test"][
            "recall_by_severity"
        ]
        lines.append(
            f"| {_label(name)} | "
            + " | ".join(f"{bins[0]['recall']:.2f}" for bins in sev.values())
            + " |"
        )
    return "\n".join(lines) + "\n"


def _degraded_classes(run_dir: Path, model: str) -> list[str]:
    metrics = json.loads((run_dir / model / "metrics.json").read_text())
    return list(metrics["test"]["recall_by_severity"])


def write(run_dir: str | Path, path: str | Path = "reports/results.md") -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(run_dir), encoding="utf-8")
    return path
